#include "ordax/mobile/cpu_a64.hpp"
#include "ordax/mobile/elf_a64.hpp"

#include <array>
#include <cassert>
#include <cstdint>
#include <iostream>
#include <fstream>
#include <string>
#include <vector>

using ordax::mobile::CpuA64;
using ordax::mobile::GuestFault;

static void encode(std::array<std::uint8_t, 32>& code, std::size_t slot, std::uint32_t ins) {
    for (unsigned j = 0; j < 4; ++j) code[slot * 4 + j] = static_cast<std::uint8_t>(ins >> (j * 8));
}
template <typename F> static void must_fault(F&& fn) {
    bool thrown = false;
    try { fn(); } catch (const GuestFault&) { thrown = true; }
    assert(thrown);
}
static bool emit_i32_fixture(const char* path) {
    // Executable AArch64 ELF64: ADD X0,X0,#2 ; RET X30.
    // The return value MUST depend on an argument supplied by the host.
    std::vector<std::uint8_t> elf(0x108, 0);
    const auto put16 = [&elf](std::size_t p, std::uint16_t v) {
        for (unsigned i = 0; i < 2; ++i) elf[p + i] = static_cast<std::uint8_t>(v >> (8 * i));
    };
    const auto put32 = [&elf](std::size_t p, std::uint32_t v) {
        for (unsigned i = 0; i < 4; ++i) elf[p + i] = static_cast<std::uint8_t>(v >> (8 * i));
    };
    const auto put64 = [&elf](std::size_t p, std::uint64_t v) {
        for (unsigned i = 0; i < 8; ++i) elf[p + i] = static_cast<std::uint8_t>(v >> (8 * i));
    };
    elf[0] = 0x7f; elf[1] = 'E'; elf[2] = 'L'; elf[3] = 'F';
    elf[4] = 2; elf[5] = 1; elf[6] = 1;
    put16(16, 2); put16(18, 183); put32(20, 1); put64(24, 0x1000);
    put64(32, 64); put16(52, 64); put16(54, 56); put16(56, 1);
    put32(64, 1); put32(68, 5); put64(72, 0x100); put64(80, 0x1000);
    put64(88, 0x1000); put64(96, 8); put64(104, 8); put64(112, 0x1000);
    put32(0x100, 0x91000800); // ADD X0,X0,#2
    put32(0x104, 0xd65f03c0); // RET X30
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    return out.write(reinterpret_cast<const char*>(elf.data()),
                     static_cast<std::streamsize>(elf.size())).good();
}

int main(int argc, char** argv) {
    if (argc == 3 && std::string(argv[1]) == "--emit-i32-fixture") {
        return emit_i32_fixture(argv[2]) ? 0 : 3;
    }
    if (argc != 1) return 2;
    // Return 42 from actual decoded MOVZ/ADD/RET instructions.
    {
        CpuA64 cpu(4096);
        std::array<std::uint8_t, 32> code{};
        encode(code, 0, 0xd2800000u | (40u << 5)); // movz x0,#40
        encode(code, 1, 0x91000000u | (2u << 10)); // add x0,x0,#2
        encode(code, 2, 0xd65f03c0u); // ret x30
        cpu.load(0, code);
        assert(cpu.run(0, 20) == 42);
    }
    // Store/load a 64-bit value in a guest allocation, never a host pointer.
    {
        CpuA64 cpu(4096);
        std::array<std::uint8_t, 32> code{};
        encode(code, 0, 0xd2800000u | (42u << 5)); // movz x0,#42
        encode(code, 1, 0xd2800001u | (256u << 5)); // movz x1,#256
        encode(code, 2, 0xf9000020u); // str x0,[x1]
        encode(code, 3, 0xd2800000u); // movz x0,#0
        encode(code, 4, 0xf9400020u); // ldr x0,[x1]
        encode(code, 5, 0xd65f03c0u); // ret
        cpu.load(0, code);
        assert(cpu.run(0, 20) == 42);
    }
    // MOV (register) is the ORR Xd,XZR,Xm alias generated by LLVM Clang.
    // Test the real 64-bit logical operation, register-31 zero semantics
    // and a nonzero logical shift without special-casing the compiler output.
    {
        CpuA64 cpu(4096);
        std::array<std::uint8_t, 32> code{};
        encode(code, 0, 0xd2800502u); // movz x2,#40
        encode(code, 1, 0xaa0203e0u); // orr x0,xzr,x2 = mov x0,x2
        encode(code, 2, 0xaa020400u); // orr x0,x0,x2,lsl #1 -> 40|80=120
        encode(code, 3, 0xd65f03c0u); // ret
        cpu.load(0, code);
        assert(cpu.run(0, 20) == 120);
    }
    // Branch loop MUST stop on instruction budget (no hang).
    {
        CpuA64 cpu(4096);
        std::array<std::uint8_t, 4> code{0, 0, 0, 0x14}; // b .
        cpu.load(0, code);
        must_fault([&] { (void)cpu.run(0, 8); });
    }
    // Unknown instructions and out-of-bounds access fail closed.
    {
        CpuA64 cpu(4096);
        std::array<std::uint8_t, 4> code{0xff, 0xff, 0xff, 0xff};
        cpu.load(0, code);
        must_fault([&] { (void)cpu.run(0, 8); });
        must_fault([&] { cpu.load(4094, code); });
        must_fault([&] { (void)cpu.run(4096, 8); });
    }

    // Parse and execute a REAL static AArch64 ELF64, not an invented instruction buffer.
    {
        std::vector<std::uint8_t> elf(0x100 + 12, 0);
        auto put16 = [&elf](std::size_t p, std::uint16_t value) {
            for (unsigned i = 0; i < 2; i++) elf[p + i] = static_cast<std::uint8_t>(value >> (8 * i));
        };
        auto put32 = [&elf](std::size_t p, std::uint32_t value) {
            for (unsigned i = 0; i < 4; i++) elf[p + i] = static_cast<std::uint8_t>(value >> (8 * i));
        };
        auto put64 = [&elf](std::size_t p, std::uint64_t value) {
            for (unsigned i = 0; i < 8; i++) elf[p + i] = static_cast<std::uint8_t>(value >> (8 * i));
        };
        elf[0] = 0x7f; elf[1] = 'E'; elf[2] = 'L'; elf[3] = 'F';
        elf[4] = 2; elf[5] = 1; elf[6] = 1;
        put16(16, 2); put16(18, 183); put32(20, 1); put64(24, 0x1000);
        put64(32, 64); put16(52, 64); put16(54, 56); put16(56, 1);
        put32(64, 1); put32(68, 5); put64(72, 0x100);
        put64(80, 0x1000); put64(88, 0x1000); put64(96, 12);
        put64(104, 16); put64(112, 0x1000);
        put32(0x100, 0xd2800000u | (42u << 5));
        put32(0x104, 0xd65f03c0u);
        CpuA64 cpu(8192);
        auto image = ordax::mobile::loadStaticElfA64(cpu, elf);
        assert(image.entry == 0x1000 && image.load_segments == 1);
        assert(cpu.run(image.entry, 20) == 42);
        put64(24, 0x2000); // entry outside executable mapped segment
        must_fault([&] { (void)ordax::mobile::loadStaticElfA64(cpu, elf); });
        put64(24, 0x1000);
        put32(64, 2); // PT_DYNAMIC: must not silently ignore linkage
        must_fault([&] { (void)ordax::mobile::loadStaticElfA64(cpu, elf); });
    }
    std::cout << "AArch64 bounded instruction proof passed\n";
}
