function memory(t){
 const store=new Store(':memory:');
 t.after(()=>store.close());
 const task=store.createTask('W5 provisional');
 const {runId}=store.beginProviderRun(task.id,'synthetic local prompt');
 return {store,task,runId};
}
const count=(store,table)=>store.db.prepare('SELECT COUNT(*) n FROM '+table).get().n;
test('provisional stays unverified, task-scoped, bounded and outside messages/events/checkpoints',t=>{
 const {store,task,runId}=memory(t);
 const other=store.createTask('other');
 const messages=count(store,'messages'),events=count(store,'events');
 assert.equal(store.saveRunProvisionalOutput(task.id,runId,'resposta parcial','beta'),true);
 assert.equal(store.saveRunProvisionalOutput(task.id,runId,'resposta parcial','beta'),false);
 assert.equal(store.saveRunProvisionalOutput(task.id,runId,'corta','beta'),false);
 assert.equal(store.saveRunProvisionalOutput(task.id,runId,'resposta parcial atualizada','dom'),true);
 assert.deepEqual(store.getTask(other.id).provisional_response,null);
 const snapshot=store.getTask(task.id).provisional_response;
 assert.equal(snapshot.run_id,runId);
 assert.equal(snapshot.content,'resposta parcial atualizada');
 assert.equal(snapshot.observed_kind,'unverified');
 assert.equal(snapshot.source,'dom');
 assert.equal(count(store,'run_provisional_outputs'),1);
 assert.equal(count(store,'messages'),messages);
 assert.equal(count(store,'events'),events);
 assert.equal(count(store,'checkpoints'),0);
 assert.throws(()=>store.saveRunProvisionalOutput(other.id,runId,'vazamento'),/provisional_run_not_running/);
 assert.throws(()=>store.saveRunProvisionalOutput(task.id,runId,'abc','unexpected'),/invalid_provisional_source/);
 assert.throws(()=>store.saveRunProvisionalOutput(task.id,runId,'   '),/invalid_provisional_content/);
 assert.throws(()=>store.saveRunProvisionalOutput(task.id,runId,'a'.repeat(262145)),/provisional_input_too_large/);
 assert.equal(store.saveRunProvisionalOutput(task.id,runId,'x'.repeat(70000)),true);
 assert.equal(store.getTask(task.id).provisional_response.content.length,65536);
});
test('one durable provisional survives SQLite restart and interrupted recovery, never creates a successful reply',t=>{
 const folder=fs.mkdtempSync(path.join(os.tmpdir(),'ordax-provisional-restart-'));
 const dbPath=path.join(folder,'lab.sqlite');
 let store=new Store(dbPath);
 t.after(()=>{store?.close();fs.rmSync(folder,{recursive:true,force:true});});
 const task=store.createTask('isolated W5 partial');
 const {runId}=store.beginProviderRun(task.id,'synthetic prompt');
 store.saveRunProvisionalOutput(task.id,runId,'texto observado ainda incompleto','beta');
 store.close();
 store=new Store(dbPath);
 assert.equal(store.recoverInterruptedRuns(),1);
 assert.equal(store.recoverInterruptedRuns(),0);
 assert.equal(store.getTask(task.id).provisional_response.content,'texto observado ainda incompleto');
 assert.equal(store.getTask(task.id).provisional_response.observed_kind,'unverified');
 assert.equal(count(store,'messages'),1);
 assert.equal(count(store,'conversation_completed_runs'),0);
 assert.equal(store.db.prepare("SELECT COUNT(*) n FROM events WHERE kind='run.succeeded'").get().n,0);
 assert.equal(store.db.prepare("SELECT status FROM runs WHERE id=?").get(runId).status,'interrupted');
 assert.throws(()=>store.saveRunProvisionalOutput(task.id,runId,'should never resume automatically'),/provisional_run_not_running/);
 assert.equal(store.db.prepare('PRAGMA quick_check(1)').get().quick_check,'ok');
});
test('success atomically removes temporary output, error preserves it for reconciliation',t=>{
 const {store,task,runId}=memory(t);
 store.saveRunProvisionalOutput(task.id,runId,'incomplete','beta');
 store.appendMessage(task.id,'assistant','confirmed answer');
 store.finishRun(task.id,runId);
 assert.equal(store.getRunProvisionalOutput(task.id),null);
 assert.equal(count(store,'run_provisional_outputs'),0);
 assert.equal(count(store,'messages'),2);
 const other=store.createTask('error path');
 const failed=store.beginProviderRun(other.id,'other prompt');
 store.saveRunProvisionalOutput(other.id,failed.runId,'partial error path');
 store.finishRun(other.id,failed.runId,'response_not_observed');
 assert.equal(store.getTask(other.id).provisional_response.content,'partial error path');
 assert.equal(store.db.prepare("SELECT status FROM runs WHERE id=?").get(failed.runId).status,'failed');
});
test('failure of transactional finish rolls back temporary deletion and terminal Run state',t=>{
 const {store,task,runId}=memory(t);
 store.saveRunProvisionalOutput(task.id,runId,'saved before disk exception');
 store.db.exec("CREATE TEMP TRIGGER reject_completed BEFORE INSERT ON events WHEN NEW.kind='run.succeeded' BEGIN SELECT RAISE(ABORT,'failed_completion_event'); END");
 assert.throws(()=>store.finishRun(task.id,runId),/failed_completion_event/);
 assert.equal(store.db.prepare('SELECT status FROM runs WHERE id=?').get(runId).status,'running');
 assert.equal(store.getRunProvisionalOutput(task.id).content,'saved before disk exception');
 assert.equal(store.recoverInterruptedRuns(),1);
 assert.equal(store.getTask(task.id).provisional_response.observed_kind,'unverified');
});
test('failed deletion rolls back success and keeps the original unverified snapshot',t=>{
 const {store,task,runId}=memory(t);
 store.saveRunProvisionalOutput(task.id,runId,'recoverable partial');
 store.db.exec("CREATE TEMP TRIGGER reject_provisional_delete BEFORE DELETE ON run_provisional_outputs BEGIN SELECT RAISE(ABORT,'provisional_delete_denied'); END");
 assert.throws(()=>store.finishRun(task.id,runId),/provisional_delete_denied/);
 assert.equal(store.db.prepare('SELECT status FROM runs WHERE id=?').get(runId).status,'running');
 assert.equal(store.getRunProvisionalOutput(task.id).content,'recoverable partial');
 assert.equal(store.db.prepare("SELECT COUNT(*) n FROM events WHERE kind='run.succeeded'").get().n,0);
 store.db.exec('DROP TRIGGER reject_provisional_delete');
 assert.equal(store.recoverInterruptedRuns(),1);
 assert.equal(store.getTask(task.id).provisional_response.observed_kind,'unverified');
});
test('latest completed Run hides older error Run provisional output',t=>{
 const {store,task,runId}=memory(t);
 store.saveRunProvisionalOutput(task.id,runId,'earlier unverified');
 store.finishRun(task.id,runId,'failed_before_completion');
 assert.equal(store.getTask(task.id).provisional_response?.content,'earlier unverified');
 const second=store.beginProviderRun(task.id,'second synthetic user turn');
 store.appendMessage(task.id,'assistant','newly confirmed');
 store.finishRun(task.id,second.runId);
 assert.equal(store.getTask(task.id).provisional_response,null);
 assert.equal(store.db.prepare('SELECT COUNT(*) n FROM run_provisional_outputs').get().n,1);
});
test('throttled recorder writes first and latest observations, never one row per token',()=>{
 let clock=0;
 const writes=[];
 const sink=createProviderProvisionalRecorder({now:()=>clock,intervalMs:2000,
  save:(text,source)=>{writes.push([text,source,clock]);return true;}});
 assert.equal(sink.capture('a'),true);
 assert.equal(sink.capture('ab'),false);
 clock=500;
 assert.equal(sink.capture('abc'),false);
 clock=1900;
 assert.equal(sink.capture('abcd'),false);
 assert.deepEqual(writes,[['a','beta',0]]);
 clock=2000;
 assert.equal(sink.capture('abcde','dom'),true);
 clock=2200;
 sink.capture('abcdef','dom');
 assert.equal(sink.flush(),true);
 assert.deepEqual(writes,[['a','beta',0],['abcde','dom',2000],['abcdef','dom',2200]]);
 assert.equal(sink.flush(),false);
 assert.equal(sink.capture('ab'),false);
 assert.equal(writes.length,3);
});
test('provisional disk errors do not propagate to worker or cause a submission retry',()=>{
 let clock=0,calls=0;
 const sink=createProviderProvisionalRecorder({now:()=>clock,save:()=>{calls++;throw Error('disk_failure')}});
 assert.doesNotThrow(()=>sink.capture('partial'));
 clock=2000;
 assert.doesNotThrow(()=>sink.capture('more complete observation'));
 assert.doesNotThrow(()=>sink.flush());
 assert.equal(sink.failures,3);
 assert.equal(calls,3);
});
